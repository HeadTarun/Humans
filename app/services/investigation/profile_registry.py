"""
services/investigation/profile_registry.py

Static configuration-driven Investigation Profile Registry.

Each profile maps an AttackHypothesisType to an InvestigationProfile
that declares which tools are mandatory / optional / expensive.

DESIGN RULES:
    - All 13 attack hypothesis types must have a profile.
    - Tool names are stable string identifiers from the Tool Registry.
    - Do NOT execute tools here. This is metadata only.
    - Profiles are consumed by profile_selector (policy engine).
    - Profiles must not be generated by an LLM.
    - Adding a new profile requires updating this file, not dynamic code.

TOOL NAME CONVENTIONS:
    Tool names match keys in TOOL_REGISTRY (tool_registry.py).
    They are stable identifiers — never generate them from email content.
"""

