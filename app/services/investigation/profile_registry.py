T_GROQ_REASONING = "groq_reasoning"

# IOC enrichment is Level-2 optional work. It must never preempt required
# deterministic parsing or L1 content analysis.
# Input mapping skips a lookup when the email has no matching domain, URL, or
# relay IP, so this does not create meaningless provider calls.
LEVEL0_INTELLIGENCE_TOOLS = [
    T_RDAP_DOMAIN_LOOKUP,
    T_URL_REPUTATION,
    T_IP_GEOLOCATION,
    T_IP_REPUTATION,
]


def _with_level0_intelligence(tools: list[str]) -> list[str]:
    """Return profile-specific tools plus the mandatory Level-0 IOC set."""
    return list(dict.fromkeys([*tools, *LEVEL0_INTELLIGENCE_TOOLS]))


